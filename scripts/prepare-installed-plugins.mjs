import { existsSync, mkdirSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

// Private packages are installed separately and must not be required by a public checkout.
const root = new URL('../', import.meta.url)
const target = new URL('apps/studio/hosso.installed.ts', root)
// Thứ tự là thứ tự đăng ký plugin: shipping trước promotions (xem docs/PLUGIN-COMMERCE).
const installed = ['wim', 'cross-sell', 'shipping', 'promotions', 'payment', 'notify', 'analytics', 'reports', 'accounts'].filter((id) => existsSync(new URL(`packages/plugin-${id}/src/index.ts`, root)))
for (const id of installed) if (!existsSync(new URL(`packages/plugin-${id}/src/browser.ts`, root))) {
  throw new Error(`Installed plugin ${id} needs a browser-safe src/browser.ts entry. Upgrade the separately installed package before building Studio.`)
}
for (const id of installed) {
  const scope = new URL('apps/studio/node_modules/@hosso/', root)
  mkdirSync(scope, { recursive: true })
  const link = new URL(`plugin-${id}`, scope)
  if (!existsSync(link)) symlinkSync(fileURLToPath(new URL(`packages/plugin-${id}/`, root)), fileURLToPath(link), process.platform === 'win32' ? 'junction' : 'dir')
}
const source = '// Generated by scripts/prepare-installed-plugins.mjs; never commit private registrations.\n' +
  "import type { HossoPlugin } from '@hosso/studio-blocks'\n" +
  installed.map((id, i) => `import plugin${i} from '../../packages/plugin-${id}/src/index'\n`).join('') +
  `export default [${installed.map((_, i) => `plugin${i}`).join(', ')}] satisfies HossoPlugin[]\n`
if (!existsSync(target) || readFileSync(target, 'utf8') !== source) writeFileSync(target, source)
const browserTarget = new URL('apps/studio/hosso.installed.browser.ts', root)
const browserSource = source.replaceAll('/src/index', '/src/browser')
if (!existsSync(browserTarget) || readFileSync(browserTarget, 'utf8') !== browserSource) writeFileSync(browserTarget, browserSource)
console.log(`Prepared ${installed.length} separately installed plugin(s): ${fileURLToPath(target)}`)
