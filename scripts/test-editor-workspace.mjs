import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { join } from 'node:path'

const require = createRequire(new URL('../apps/studio/package.json', import.meta.url))
const { chromium } = require(process.env.HOSSO_PLAYWRIGHT_MODULE || 'playwright')
const origin = process.env.HOSSO_EDITOR_ORIGIN || 'http://localhost:3111'
assert.ok(/^http:\/\/localhost:\d+$/.test(origin), 'Only use the disposable local fixture')
const output = new URL('../output/editor-workspace-20261104/', import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1')
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, extraHTTPHeaders: { Origin: origin } })
  await context.addInitScript(() => localStorage.setItem('hosso-editor-intro:v2', 'done'))
  await context.route(/https:\/\/(fonts\.googleapis\.com|fonts\.gstatic\.com)/, (route) => route.abort())
  const login = await context.request.post(origin + '/api/users/login', { timeout: 120000, data: { email: 'browser@studio.test', password: 'studio-browser-test-password' } })
  assert.ok(login.ok(), await login.text())
  const fixture = await context.request.get(origin + '/api/pages/1?draft=true')
  assert.equal((await fixture.json()).title, 'Studio test', 'Refuse edits outside the fixture')
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error' && /hydration|cannot be a descendant|cannot contain a nested/i.test(message.text())) errors.push(message.text()) })
  await page.goto(origin + '/editor/1?block=hero', { timeout: 120000 })
  await page.locator('.cv-editor[data-focus=true]').waitFor({ timeout: 120000 })
  const frame = page.locator('iframe[title="Trang"]').contentFrame()
  await frame.locator('[data-element="headline"]').waitFor()
  const viewport = await page.locator('[data-canvas-viewport]').boundingBox()
  assert.ok(viewport.width > 1550, 'Focus canvas fills the workspace')
  assert.ok(viewport.height > 880)
  const dock = page.locator('.cv-floating-dock[data-floating=true]')
  const grip = page.getByRole('button', { name: 'Kéo bộ công cụ', exact: true })
  const initialDock = await dock.boundingBox()
  const gripBox = await grip.boundingBox()
  await page.mouse.move(gripBox.x + 20, gripBox.y + 12)
  await page.mouse.down(); await page.mouse.move(gripBox.x + 130, gripBox.y + 80, { steps: 8 }); await page.mouse.up()
  const movedDock = await dock.boundingBox()
  assert.ok(movedDock.x > initialDock.x + 80 && movedDock.y > initialDock.y + 40)
  await grip.dblclick()
  assert.ok(Math.abs((await dock.boundingBox()).x - initialDock.x) < 2)
  await frame.locator('[data-element="headline"]').click({ position: { x: 80, y: 40 } })
  const toolbar = frame.getByRole('toolbar', { name: 'Chỉnh sửa phần tử' })
  await toolbar.waitFor()
  const before = await toolbar.boundingBox()
  const elementGrip = frame.getByRole('button', { name: 'Kéo thanh công cụ', exact: true })
  await elementGrip.focus(); await elementGrip.press('ArrowDown'); await elementGrip.press('ArrowDown')
  const after = await toolbar.boundingBox()
  assert.ok(after.y >= before.y + 15, 'Toolbar keyboard drag changes its position')
  const toolGripBox = await elementGrip.boundingBox()
  await page.mouse.move(toolGripBox.x + 8, toolGripBox.y + 10)
  await page.mouse.down(); await page.mouse.move(toolGripBox.x + 75, toolGripBox.y + 80, { steps: 8 }); await page.mouse.up()
  assert.ok((await toolbar.boundingBox()).y > after.y + 50, 'Pointer dragging moves the contextual toolbar')
  await elementGrip.press('Home')
  await toolbar.getByRole('spinbutton', { name: 'Cỡ chữ', exact: true }).fill('52')
  const [saveResponse] = await Promise.all([page.waitForResponse((res) => res.url().includes('/api/pages/1') && res.request().method() === 'PATCH'), page.getByRole('button', { name: 'Lưu nháp', exact: true }).click()])
  assert.ok(saveResponse.ok(), await saveResponse.text())
  console.log('Saved draft status', saveResponse.status())
  const saved = await context.request.get(origin + '/api/pages/1?draft=true')
  assert.ok(saved.ok(), `Saved page ${saved.status()}: ${await saved.text()}`)
  assert.equal((await saved.json()).content.content[0].props._els.find((el) => el.id === 'headline').props.size, 52)
  const rail = page.getByRole('navigation', { name: 'Công cụ', exact: true })
  await rail.getByRole('button', { name: 'Lịch sử', exact: true }).click()
  await page.getByRole('textbox', { name: 'Tên snapshot', exact: true }).fill('Trước khi đổi bố cục')
  await page.getByRole('button', { name: 'Lưu snapshot', exact: true }).click()
  assert.ok(await page.getByText('Trước khi đổi bố cục', { exact: true }).isVisible())
  await rail.getByRole('button', { name: 'Cấu trúc', exact: true }).click()
  assert.equal(await page.locator('.cv-layer-row').count(), 2)
  await page.locator('.cv-layer-row input[type=checkbox]').nth(0).check()
  await page.locator('.cv-layer-row input[type=checkbox]').nth(1).check()
  await page.getByRole('button', { name: 'Gom nhóm', exact: true }).click()
  assert.equal(await page.locator('.cv-layer-row').count(), 3)
  await page.getByRole('button', { name: 'Tách nhóm', exact: true }).click()
  assert.equal(await page.locator('.cv-layer-row').count(), 2)
  await rail.getByRole('button', { name: 'Kho mẫu', exact: true }).click()
  await page.getByRole('textbox', { name: 'Tên mẫu section', exact: true }).fill('Section kiểm thử')
  await page.getByRole('button', { name: 'Lưu mẫu', exact: true }).click()
  await page.locator('.cv-reusable-item').filter({ hasText: 'Section kiểm thử' }).first().waitFor()
  const sectionCount = await frame.locator('[data-block]').count()
  await page.locator('.cv-reusable-item').first().getByRole('button', { name: 'Chèn bản sao', exact: true }).click()
  assert.equal(await frame.locator('[data-block]').count(), sectionCount + 1)
  await page.getByRole('button', { name: 'Hoàn tác', exact: true }).filter({ visible: true }).click()
  assert.equal(await frame.locator('[data-block]').count(), sectionCount)
  await rail.getByRole('button', { name: 'Ảnh/Video', exact: true }).click()
  await page.locator('.cv-media-upload input').setInputFiles(new URL('../apps/studio/public/editor-templates/workspace.jpg', import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1'))
  await page.locator('.cv-media-item').first().waitFor()
  await page.locator('.cv-media-edit').first().click()
  const imageEditor = page.getByRole('dialog', { name: /Sửa ảnh|Edit image/ })
  await imageEditor.waitFor()
  await imageEditor.getByRole('button', { name: /Lưu thành ảnh mới|Save as new image/ }).click()
  await imageEditor.waitFor({ state: 'detached' })
  assert.ok(await page.locator('.cv-media-item').count() >= 2)
  await rail.getByRole('button', { name: 'Thiết bị', exact: true }).click()
  await page.locator('.cv-tool-segments').getByRole('button', { name: /Mobile/ }).click()
  assert.ok((await page.locator('iframe[title="Trang"]').boundingBox()).width <= 391)
  await page.getByRole('button', { name: 'Tự xếp dọc toàn trang', exact: true }).click()
  await page.locator('.cv-tool-segments').getByRole('button', { name: /Desktop/ }).click()
  await rail.getByRole('button', { name: 'Kiểm tra', exact: true }).click()
  await page.getByRole('textbox', { name: /^Tiêu đề SEO/ }).fill('Studio thiết kế tự do')
  await page.getByRole('button', { name: 'Lưu SEO nháp', exact: true }).click()
  await page.getByText('Đã lưu SEO vào bản nháp.', { exact: true }).waitFor()
  const seo = await context.request.get(origin + '/api/pages/1?draft=true')
  assert.equal((await seo.json()).seo.title, 'Studio thiết kế tự do')
  await rail.getByRole('button', { name: 'Nhập liệu', exact: true }).click()
  await page.getByRole('button', { name: 'Tạo biểu mẫu', exact: true }).click()
  const formTitle = 'Tư vấn Studio ' + Date.now()
  await page.getByRole('textbox', { name: 'Tên biểu mẫu', exact: true }).fill(formTitle)
  await page.getByText('Sau khi gửi và kết nối CRM', { exact: true }).click()
  await page.getByRole('textbox', { name: 'Trang cảm ơn', exact: true }).fill('/cam-on')
  await page.getByRole('button', { name: 'Lưu biểu mẫu', exact: true }).click()
  await page.getByText('Đã lưu định nghĩa biểu mẫu.', { exact: true }).waitFor()
  const forms = await context.request.get(origin + '/api/forms?depth=0')
  const form = (await forms.json()).docs.find((doc) => doc.title === formTitle)
  assert.ok(form)
  const anonymous = await browser.newContext()
  const publicForm = await anonymous.request.get(origin + '/api/forms/' + form.id)
  assert.equal((await publicForm.json()).delivery, undefined, 'Public API must not expose delivery configuration')
  await anonymous.close()
  const invalid = await context.request.post(origin + '/api/site/forms/' + form.slug, { data: { values: { name: 'Khách thử', email: 'invalid' } } })
  assert.equal(invalid.status(), 400)
  const submission = await context.request.post(origin + '/api/site/forms/' + form.slug, { data: { values: { name: 'Khách thử', email: 'studio@example.com', phone: '0901234567' } } })
  assert.ok(submission.ok(), await submission.text())
  assert.equal((await submission.json()).redirect, '/cam-on')
  await page.getByRole('button', { name: 'Thu gọn bảng công cụ', exact: true }).click()
  await page.getByRole('button', { name: 'Toàn màn hình', exact: true }).click()
  await page.locator('.cv-editor[data-fullscreen=true]').waitFor()
  await page.screenshot({ path: join(output, 'editor-fullscreen.png') })
  await page.keyboard.press('Escape')
  // Headless Chromium may not map Escape to its native fullscreen UI.
  if (await page.locator('.cv-editor[data-fullscreen=true]').count()) await page.getByRole('button', { name: 'Thoát toàn màn hình', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: join(output, 'editor-mobile.png') })
  const rootWidth = await page.locator('.cv-editor').evaluate((el) => el.scrollWidth)
  assert.ok(rootWidth <= 392, 'Editor controls do not cause horizontal overflow')
  assert.deepEqual(errors, [])
  console.log('PASS canvas space, movable docks, element toolbar, text persistence, snapshots, groups, devices, SEO, form validation/submission and fullscreen')
} finally { await browser.close() }
